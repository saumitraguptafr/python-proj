#return-statement use to end a function and send back the result to the caller
def add(x,y):
    z = x + y
    return z
def subtract(x,y):
    z = x - y
    return z
def multiply(x,y):
    z = x * y
    return z
def divide(x,y):
    z = x/y
    return z

print(add(5,4))
#basically thing is alternaively shown as print(9)
print(subtract(5,4))
#print(1) basically
print(multiply(5,4))
#print(20)
print(divide(20,5))
